IF OBJECT_ID('dbo.FIRMASHOJAVIDA', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.FIRMASHOJAVIDA (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    IDACTIVO INT NOT NULL,
    TIPO VARCHAR(20) NOT NULL,
    NOMBRE NVARCHAR(100) NOT NULL,
    IMAGEN VARBINARY(MAX) NOT NULL,
    FECHAFIRMA DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    IDUSUARIO INT NOT NULL,
    CONSTRAINT UQ_FIRMASHOJAVIDA_ACTIVO_TIPO UNIQUE (IDACTIVO, TIPO),
    CONSTRAINT CK_FIRMASHOJAVIDA_TIPO CHECK (TIPO IN ('COORDINADOR', 'DESIGNADO')),
    CONSTRAINT FK_FIRMASHOJAVIDA_ACTIVO FOREIGN KEY (IDACTIVO) REFERENCES dbo.INVENTARIOSMESA(ID) ON DELETE CASCADE
  );
END;
