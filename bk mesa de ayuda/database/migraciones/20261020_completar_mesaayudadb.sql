-- Completa las tablas faltantes usando MESAAYUDADB80 como referencia estructural.
-- No copia tickets, usuarios, firmas ni archivos entre bases.
USE [MESAAYUDADB];
SET XACT_ABORT ON;
BEGIN TRY
  BEGIN TRANSACTION;
  IF OBJECT_ID('dbo.ACHIVOSMANTENIMIENTO','U') IS NULL
  BEGIN
    CREATE TABLE dbo.ACHIVOSMANTENIMIENTO (
      ID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_ACHIVOSMANTENIMIENTO PRIMARY KEY CLUSTERED,
      IDMANTENIMIENTO INT NOT NULL,
      NOMBREARCHIVO VARCHAR(250) COLLATE Modern_Spanish_CI_AS NULL,
      URLARCHIVO VARCHAR(999) COLLATE Modern_Spanish_CI_AS NOT NULL,
      TIPOARCHIVO VARCHAR(50) COLLATE Modern_Spanish_CI_AS NULL,
      FECHAREGISTRO DATETIME2(7) NULL CONSTRAINT DF_ACHIVOSMANTENIMIENTO_FECHA DEFAULT SYSDATETIME(),
      CONSTRAINT FK_ARCHIVO_MANTENIMIENTOS FOREIGN KEY (IDMANTENIMIENTO) REFERENCES dbo.MANTENIMIENTOSMESA(ID)
    );
  END;
  IF OBJECT_ID('dbo.FIRMASHOJAVIDA','U') IS NULL
  BEGIN
    CREATE TABLE dbo.FIRMASHOJAVIDA (
      ID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_FIRMASHOJAVIDA PRIMARY KEY CLUSTERED,
      IDACTIVO INT NOT NULL,
      TIPO VARCHAR(20) COLLATE Modern_Spanish_CI_AS NOT NULL,
      NOMBRE NVARCHAR(100) COLLATE Modern_Spanish_CI_AS NOT NULL,
      IMAGEN VARBINARY(MAX) NOT NULL,
      FECHAFIRMA DATETIME2(7) NOT NULL CONSTRAINT DF_FIRMASHOJAVIDA_FECHA DEFAULT SYSUTCDATETIME(),
      IDUSUARIO INT NOT NULL,
      IDFIRMANTE INT NULL,
      CONSTRAINT UQ_FIRMASHOJAVIDA_ACTIVO_TIPO UNIQUE (IDACTIVO,TIPO),
      CONSTRAINT CK_FIRMASHOJAVIDA_TIPO CHECK (TIPO IN ('COORDINADOR','DESIGNADO')),
      CONSTRAINT FK_FIRMASHOJAVIDA_ACTIVO FOREIGN KEY (IDACTIVO) REFERENCES dbo.INVENTARIOSMESA(ID) ON DELETE CASCADE,
      CONSTRAINT FK_FIRMASHOJAVIDA_FIRMANTE FOREIGN KEY (IDFIRMANTE) REFERENCES dbo.USUARIOSMESA(ID)
    );
  END;
  IF OBJECT_ID('dbo.PRIORIDADESMESA','U') IS NULL
  BEGIN
    CREATE TABLE dbo.PRIORIDADESMESA (
      ID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_PRIORIDADESMESA PRIMARY KEY CLUSTERED,
      IDMESA INT NOT NULL,
      CODIGO VARCHAR(20) COLLATE Modern_Spanish_CI_AS NOT NULL,
      NOMBRE VARCHAR(100) COLLATE Modern_Spanish_CI_AS NOT NULL,
      ORDEN INT NOT NULL CONSTRAINT DF_PRIORIDADESMESA_ORDEN DEFAULT 0,
      CONSTRAINT UQ_PRIORIDADESMESA_CODIGO UNIQUE (IDMESA,CODIGO),
      CONSTRAINT FK_PRIORIDADESMESA_MESA FOREIGN KEY (IDMESA) REFERENCES dbo.MESASAYUDA(ID)
    );
  END;
  INSERT INTO dbo.PRIORIDADESMESA (IDMESA,CODIGO,NOMBRE,ORDEN)
  SELECT M.ID,V.CODIGO,V.NOMBRE,V.ORDEN
  FROM dbo.MESASAYUDA M CROSS JOIN (VALUES ('BAJA','Baja',1),('MEDIA','Media',2),('ALTA','Alta',3)) V(CODIGO,NOMBRE,ORDEN)
  WHERE NOT EXISTS (SELECT 1 FROM dbo.PRIORIDADESMESA P WHERE P.IDMESA=M.ID AND P.CODIGO=V.CODIGO);
  INSERT INTO dbo.PRIORIDADESMESA (IDMESA,CODIGO,NOMBRE,ORDEN)
  SELECT T.IDMESA,UPPER(LTRIM(RTRIM(T.PRIORIDAD))),MIN(LTRIM(RTRIM(T.PRIORIDAD))),4
  FROM dbo.TICKETSMESA T JOIN dbo.MESASAYUDA M ON M.ID=T.IDMESA
  WHERE NULLIF(LTRIM(RTRIM(T.PRIORIDAD)),'') IS NOT NULL
    AND NOT EXISTS (SELECT 1 FROM dbo.PRIORIDADESMESA P WHERE P.IDMESA=T.IDMESA AND P.CODIGO=UPPER(LTRIM(RTRIM(T.PRIORIDAD))))
  GROUP BY T.IDMESA,UPPER(LTRIM(RTRIM(T.PRIORIDAD)));
  COMMIT TRANSACTION;
END TRY
BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK TRANSACTION;
  THROW;
END CATCH;
