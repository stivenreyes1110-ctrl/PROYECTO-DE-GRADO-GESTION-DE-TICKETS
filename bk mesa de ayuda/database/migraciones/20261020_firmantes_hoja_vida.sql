SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF COL_LENGTH('dbo.FIRMASHOJAVIDA', 'IDFIRMANTE') IS NULL
  ALTER TABLE dbo.FIRMASHOJAVIDA ADD IDFIRMANTE INT NULL;
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name='FK_FIRMASHOJAVIDA_FIRMANTE' AND parent_object_id=OBJECT_ID('dbo.FIRMASHOJAVIDA'))
  ALTER TABLE dbo.FIRMASHOJAVIDA WITH CHECK ADD CONSTRAINT FK_FIRMASHOJAVIDA_FIRMANTE FOREIGN KEY (IDFIRMANTE) REFERENCES dbo.USUARIOSMESA(ID);
COMMIT TRANSACTION;
