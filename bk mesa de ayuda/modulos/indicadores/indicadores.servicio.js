const sql = require('mssql');
const {conexion} = require('../../config/db');
const {completarSerie} = require('./indicadores.validacion');
const metricas = `COUNT(*) AS TOTAL,
  COALESCE(SUM(CASE WHEN IDASIGNADO IS NOT NULL THEN 1 ELSE 0 END),0) AS ASIGNADOS,
  COALESCE(SUM(CASE WHEN ESTADO IN (2,3,4) THEN 1 ELSE 0 END),0) AS ATENDIDOS,
  COALESCE(SUM(CASE WHEN ESTADO=1 THEN 1 ELSE 0 END),0) AS POR_ASIGNAR,
  COALESCE(SUM(CASE WHEN ESTADO=2 THEN 1 ELSE 0 END),0) AS EN_PROCESO,
  COALESCE(SUM(CASE WHEN ESTADO=3 THEN 1 ELSE 0 END),0) AS SOLUCIONADOS,
  COALESCE(SUM(CASE WHEN ESTADO=4 THEN 1 ELSE 0 END),0) AS CERRADOS,
  COALESCE(SUM(CASE WHEN ESTADO IN (1,2) THEN 1 ELSE 0 END),0) AS PENDIENTES,
  COALESCE(SUM(CASE WHEN ESTADO IS NULL OR ESTADO NOT IN (1,2,3,4) THEN 1 ELSE 0 END),0) AS SIN_ESTADO,
  AVG(MINUTOS) AS PROMEDIO_MINUTOS, COUNT(MINUTOS) AS MUESTRA_TIEMPO,
  COALESCE(SUM(CASE WHEN ESTADO IN (3,4) AND MINUTOS IS NULL THEN 1 ELSE 0 END),0) AS TIEMPOS_EXCLUIDOS`;
async function consultar(contexto, filtros) {
  const pool = await conexion();
  const r = await pool.request()
    .input('IDMESA',sql.Int,Number(contexto.idMesa))
    .input('ACTOR',sql.Int,Number(contexto.idUsuario))
    .input('USUARIO',sql.Int,filtros.idUsuario)
    .input('DESDE',sql.DateTime2,filtros.desde ? new Date(`${filtros.desde}T00:00:00Z`) : null)
    .input('HASTA',sql.DateTime2,filtros.hasta ? new Date(`${filtros.hasta}T00:00:00Z`) : null)
    .input('DIARIO',sql.Bit,filtros.vista === 'mensual')
    .query(`
      SET NOCOUNT ON;
      IF NOT EXISTS (SELECT 1 FROM SOPORTESMESA S JOIN USUARIOSMESA U ON U.ID=S.IDUSUARIO
        WHERE S.IDMESA=@IDMESA AND S.IDUSUARIO=@ACTOR AND S.IDROL IN (1,2) AND U.ESTADO=1)
        THROW 50303, 'No tiene permisos para consultar indicadores de esta mesa.', 1;
      IF @USUARIO IS NOT NULL AND NOT EXISTS (SELECT 1 FROM SOPORTESMESA WHERE IDMESA=@IDMESA AND IDUSUARIO=@USUARIO)
        THROW 50300, 'El soporte seleccionado no pertenece a esta mesa.', 1;
      SELECT T.ID,T.ESTADO,T.IDAREA,T.IDSEDE,T.HORAREGISTRO,S.IDUSUARIO AS IDASIGNADO,
        COALESCE(U.NOMBRE,'Sin asignar') AS NOMBRE,
        CASE WHEN T.ESTADO IN (3,4) AND T.HORAREGISTRO IS NOT NULL AND T.HORACIERRE>=T.HORAREGISTRO
          THEN DATEDIFF_BIG(SECOND,T.HORAREGISTRO,T.HORACIERRE)/60.0 ELSE NULL END AS MINUTOS
      INTO #BASE
      FROM TICKETSMESA T
      LEFT JOIN SOPORTESMESA S ON S.ID=T.IDSOPORTE AND S.IDMESA=T.IDMESA
      LEFT JOIN USUARIOSMESA U ON U.ID=S.IDUSUARIO
      WHERE T.IDMESA=@IDMESA AND (@USUARIO IS NULL OR S.IDUSUARIO=@USUARIO)
        AND (@DESDE IS NULL OR T.HORAREGISTRO>=@DESDE)
        AND (@HASTA IS NULL OR T.HORAREGISTRO<DATEADD(DAY,1,@HASTA));
      SELECT ${metricas} FROM #BASE;
      SELECT IDASIGNADO AS IDUSUARIO, NOMBRE, ${metricas} FROM #BASE GROUP BY IDASIGNADO,NOMBRE ORDER BY TOTAL DESC,NOMBRE;
      SELECT CASE WHEN @DIARIO=1 THEN CONVERT(VARCHAR(10),HORAREGISTRO,23) ELSE CONVERT(VARCHAR(7),HORAREGISTRO,23) END AS PERIODO,
        COUNT(*) AS TOTAL,SUM(CASE WHEN ESTADO=3 THEN 1 ELSE 0 END) AS SOLUCIONADOS,SUM(CASE WHEN ESTADO=4 THEN 1 ELSE 0 END) AS CERRADOS
      FROM #BASE WHERE HORAREGISTRO IS NOT NULL
      GROUP BY CASE WHEN @DIARIO=1 THEN CONVERT(VARCHAR(10),HORAREGISTRO,23) ELSE CONVERT(VARCHAR(7),HORAREGISTRO,23) END ORDER BY PERIODO;
      SELECT COALESCE(A.NOMBRE,'Sin área') AS NOMBRE,COUNT(*) AS TOTAL FROM #BASE B LEFT JOIN AREASCLB A ON A.ID=B.IDAREA GROUP BY A.ID,A.NOMBRE ORDER BY TOTAL DESC,NOMBRE;
      SELECT COALESCE(S.NOMBRE,'Sin sede') AS NOMBRE,COUNT(*) AS TOTAL FROM #BASE B LEFT JOIN SEDESCLB S ON S.ID=B.IDSEDE GROUP BY S.ID,S.NOMBRE ORDER BY TOTAL DESC,NOMBRE;
      SELECT DISTINCT U.ID AS IDUSUARIO,U.NOMBRE,U.ESTADO FROM SOPORTESMESA S JOIN USUARIOSMESA U ON U.ID=S.IDUSUARIO WHERE S.IDMESA=@IDMESA ORDER BY U.NOMBRE;
      SELECT DISTINCT YEAR(HORAREGISTRO) AS ANIO FROM TICKETSMESA WHERE IDMESA=@IDMESA AND HORAREGISTRO IS NOT NULL ORDER BY ANIO DESC;
      DROP TABLE #BASE;
    `);
  const [resumen,usuarios,serie,areas,sedes,soportes,anios] = r.recordsets;
  return {resumen:resumen[0], usuarios, serie:completarSerie(serie,filtros), areas, sedes, soportes, anios:anios.map(a => a.ANIO), filtros};
}
module.exports = {consultar};
