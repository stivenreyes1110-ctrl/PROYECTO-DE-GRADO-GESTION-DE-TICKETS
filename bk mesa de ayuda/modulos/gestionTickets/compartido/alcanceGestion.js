const sql = require('mssql');

const seleccionGestion = `
  SELECT
    T.ID AS ID_TICKET, T.DIRIP, T.UBICACIONFISICA, T.HORAREGISTRO,
    T.HORACIERRE, T.PRIORIDAD, T.DESCRIPCION, T.CONTESTACION,
    T.IDSOPORTE, T.IDMESA, T.IDINCIDENTE, T.IDAREA, T.IDSEDE,
    T.ARCHIVO_URL, SOPORTE_USUARIO.NOMBRE AS USUARIO_ASIGNADO,
    I.NOMBRE AS INCIDENTE, A.NOMBRE AS AREA, SD.NOMBRE AS SEDE,
    M.NOMBRE AS MESA_AYUDA, SOLICITANTE.NOMBRE AS USUARIO_SOLICITANTE,
    CASE T.ESTADO
      WHEN 1 THEN 'POR ASIGNAR'
      WHEN 2 THEN 'EN PROCESO'
      WHEN 3 THEN 'SOLUCIONADO'
      WHEN 4 THEN 'CERRADO'
      ELSE 'SIN ESTADO'
    END AS ESTADO
  FROM TICKETSMESA T
  LEFT JOIN SOPORTESMESA S ON S.ID = T.IDSOPORTE AND S.IDMESA = T.IDMESA
  LEFT JOIN USUARIOSMESA SOPORTE_USUARIO ON SOPORTE_USUARIO.ID = S.IDUSUARIO
  LEFT JOIN USUARIOSMESA SOLICITANTE ON SOLICITANTE.ID = T.IDUSUARIO
  LEFT JOIN INCIDENTESMESA I ON I.ID = T.IDINCIDENTE
  LEFT JOIN AREASCLB A ON A.ID = T.IDAREA
  LEFT JOIN SEDESCLB SD ON SD.ID = T.IDSEDE
  LEFT JOIN MESASAYUDA M ON M.ID = T.IDMESA
`;

const prepararAlcance = (request, contexto) => {
  request.input('IDMESA', sql.Int, contexto.idMesa);
  if (contexto.alcance === 'MESA') return 'T.IDMESA = @IDMESA';

  request
    .input('IDUSUARIO', sql.Int, contexto.idUsuario)
    .input('IDSOPORTE', sql.Int, contexto.idSoporte);
  return `
    T.IDMESA = @IDMESA
    AND T.IDSOPORTE = @IDSOPORTE
    AND S.ID = @IDSOPORTE
    AND S.IDUSUARIO = @IDUSUARIO
    AND S.IDMESA = @IDMESA
  `;
};

module.exports = { seleccionGestion, prepararAlcance };
